type LanguageContextValue = {
  language: UiLanguage;
  setLanguage: (value: UiLanguage) => void;
  t: (text: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function savedLanguage(): UiLanguage {
  try {
    return window.localStorage.getItem(storageKey) === "en" ? "en" : "zh-CN";
  } catch {
    return "zh-CN";
  }
}

export function UiLanguageProvider({ children }: { children: ReactNode }) {
  const [language, setCurrentLanguage] = useState<UiLanguage>(savedLanguage);
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);
  const setLanguage = (value: UiLanguage) => {
    window.localStorage.setItem(storageKey, value);
    setCurrentLanguage(value);
  };
  return (
    <LanguageContext.Provider value={{
      language,
      setLanguage,
      t: (text) => language === "zh-CN" ? chinese[text] ?? text : text,
    }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useUiLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("UI language provider is missing");
  return value;
}
