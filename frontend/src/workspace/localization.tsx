export type MessageKey = keyof typeof zhCN;
type Values = Record<string, string | number>;
export type Translate = (key: MessageKey, values?: Values) => string;

function interpolate(template: string, values?: Values) {
  if (!values) return template;
  return template.replace(/\{([^}]+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name)
      ? String(values[name])
      : match
  );
}

function readInitialLocale(): Locale {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY) === "zh-CN"
      ? "zh-CN"
      : "en";
  } catch {
    return "en";
  }
}

type LanguageValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translate;
  translateKnown: (value: string) => string;
};

const LanguageContext = createContext<LanguageValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readInitialLocale);
  const setLocale = (next: Locale) => {
    setLocaleState(next);
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch {
      // Language is a presentation preference; storage failure keeps the
      // current in-memory choice without changing product authority.
    }
  };
  const t: Translate = (key, values) => interpolate(
    locale === "zh-CN" ? zhCN[key] : key,
    values,
  );
  const translateKnown = (value: string) =>
    Object.prototype.hasOwnProperty.call(zhCN, value)
      ? t(value as MessageKey)
      : value;

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  return (
    <LanguageContext.Provider
      value={{ locale, setLocale, t, translateKnown }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used within LanguageProvider");
  return value;
}
