import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "playwright-core";
const base = "http://127.0.0.1:5598/";
const evidence = new URL("../docs/validation/dogfood-day2-d2-02/", import.meta.url).pathname;
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const errors = [], requests = [];
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 950 } });
  page.on("pageerror", error => errors.push(String(error)));
  page.on("request", request => { if (request.method() === "POST") requests.push({ url: request.url(), body: request.postData() }); });
  await page.addInitScript(() => localStorage.setItem("yia.ui-language", "en"));
  await page.goto(`${base}#Following`);
  await page.getByRole("button", { name: "Add Source", exact: true }).first().click();
  await page.getByRole("button", { name: "Import local file", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "Choose local files", exact: true }).click();
  console.log("REAL_NATIVE_BROWSER_PICKER_READY", { fixture: new URL("../.var/d2-02/ui-native-fixture/two-gib.mp4", import.meta.url).pathname });
  await dialog.getByRole("button", { name: "Confirm import", exact: true }).waitFor({ timeout: 300_000 });
  assert.ok((await dialog.innerText()).includes("two-gib.mp4"));
  assert.ok((await dialog.innerText()).includes("2 GiB"));
  assert.equal(await dialog.locator('input[type="file"]').count(), 0);
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  assert.ok((await dialog.innerText()).includes("two-gib.mp4"));
  await page.screenshot({ path: join(evidence, "native-selected-two-gib.png"), fullPage: true });
  const started = Date.now();
  await dialog.getByRole("button", { name: "Confirm import", exact: true }).click();
  await dialog.getByRole("status").filter({ hasText: "Verifying imported file…" }).waitFor();
  assert.equal(await dialog.getByRole("progressbar").count(), 0);
  await page.screenshot({ path: join(evidence, "native-verifying-two-gib.png"), fullPage: true });
  await page.waitForURL(url => url.href.startsWith(`${base}#Content/`), { timeout: 120_000 });
  await page.getByRole("heading", { name: "two-gib.mp4", exact: true }).waitFor();
  const listing = await page.request.get(`${base}api/v1/videos`);
  const item = (await listing.json()).videos.find(item => item.title === "two-gib.mp4");
  assert.ok(item, "saved Content is present in normal listing");
  assert.equal(page.url(), `${base}#Content/${encodeURIComponent(item.video_id)}`);
  assert.equal(item.processing_status, "TRANSCRIPTION_UNAVAILABLE");
  const jobs = await page.evaluate(async () => (await (await fetch('/api/v1/local/native/jobs', { method: 'POST', body: '{}', headers: {'Content-Type':'application/json','X-YIA-Request':'local-ui'} })).json()).jobs);
  assert.equal(jobs[0].files[0].snapshot_method, "APFS_CLONE");
  writeFileSync(join(evidence, "native-browser-requests.json"), JSON.stringify(requests, null, 2));
  assert.ok(requests.length >= 3);
  const controls = requests.filter(request => request.url.includes('/local/native/'));
  assert.ok(controls.length >= 3);
  assert.ok(controls.every(request => request.url.startsWith(base) && request.body === '{}'));
  assert.ok(requests.every(request => !request.url.includes('/local/imports')));
  assert.deepEqual(errors, []);
  await page.screenshot({ path: join(evidence, "native-saved-two-gib.png"), fullPage: true });
  writeFileSync(join(evidence, "browser-native-import.json"), JSON.stringify({ actualBytes: 2 * 1024 ** 3, realAppKitPicker: true, nativeHttpFileBytes: 0, secondsIncludingUiPollAndFixtureProbeDelay: (Date.now() - started)/1000, snapshotMethod: jobs[0].files[0].snapshot_method, selectionSurvivesFocus: true, contentNavigation: page.url(), processingStatus: item.processing_status, requests, errors }, null, 2));
  console.log("REAL_NATIVE_BROWSER_2_GIB_ZERO_UPLOAD_D2_01_PASSED");
} finally { await browser.close(); }
